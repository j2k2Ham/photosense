using PhotoSense.Api.Endpoints;
using PhotoSense.Api.Http;
using PhotoSense.Api.Scanning;

namespace PhotoSense.Api;

/// <summary>Every address of the service below /api, with the endpoint that answers it.</summary>
public sealed class PhotoSenseRoutes
{
    /// <summary>The addresses, each answered by one of the endpoints given; <see cref="PhotoSenseApiServices.AddPhotoSenseApi"/> makes it.</summary>
    internal PhotoSenseRoutes(HealthEndpoints health, AboutEndpoints about, FoldersEndpoints folders, PhotosEndpoints photos, DuplicateGroupsEndpoints groups, ScanStatusEndpoints status,
        ScanStartEndpoints start, ScanResetEndpoints reset, ScanProgressEndpoints progress, ScanLogsEndpoints logs, OrganizeEndpoints organize, LibraryEndpoints library,
        RemovedEndpoints removed, TransferEndpoints transfer, PlanEndpoints plan, ScanFoundEndpoints found, PairingEndpoints pairing, BackupEndpoints backup, SwipeEndpoints swipe, CategoryEndpoints categories,
        CompressionEndpoints compress, NoticeEndpoints notices, YearEndpoints year, ViewerEndpoints viewer, TripEndpoints trips, FixEndpoints fixes, VaultEndpoints vault)
    {
        Router = new ApiRouter()
            .Get("health", (r, _, ct) => health.GetAsync(r, ct))
            .Get("about", (r, _, ct) => about.GetAsync(r, ct))
            .Get("about/icon", (r, _, ct) => about.IconAsync(r, ct))
            .Get("about/{document}", (r, v, ct) => about.TextAsync(r, v["document"], ct))
            .Get("folders", (r, _, ct) => folders.BrowseAsync(r, ct))
            .Get("library/access", (r, _, ct) => library.AccessAsync(r, ct))
            .Post("library/ask", (r, _, ct) => library.AskAsync(r, ct))
            .Post("library/choose-more", (r, _, ct) => library.ChooseMoreAsync(r, ct))
            // Opening the settings is done at once, with nothing to wait for or stop.
            .Post("library/open-settings", (r, _, _) => Task.FromResult(library.OpenSettings(r)))
            .Get("photos/{id:guid}/thumbnail", (r, v, ct) => photos.GetThumbnailAsync(r, v["id"], ct))
            .Get("photos/{id:guid}/image", (r, v, ct) => photos.GetImageAsync(r, v["id"], ct))
            .Get("photos/{id:guid}/video", (r, v, ct) => photos.GetVideoAsync(r, v["id"], ct))
            .Post("photos/{id:guid}/open", (r, v, ct) => photos.OpenPhotoAsync(r, v["id"], ct))
            .Delete("photos/{id:guid}", (r, v, ct) => photos.DeletePhotoAsync(r, v["id"], ct))
            .Post("photos/{id:guid}/keep", (r, v, ct) => photos.KeepPhotoAsync(r, v["id"], ct))
            .Post("photos/bulk/remove-duplicates", (r, _, ct) => photos.RemoveDuplicatesAsync(r, ct))
            .Get("scan/status", (r, _, ct) => status.GetStatusAsync(r, ct))
            .Get("scan/groups", (r, _, ct) => groups.GetDuplicateGroupsAsync(r, ct))
            .Post("scan/start", (r, _, ct) => start.StartAsync(r, ct))
            .Post("scan/stop/{instanceId}", (r, v, ct) => start.StopAsync(r, v["instanceId"], ct))
            .Post("scan/reset", (r, _, ct) => reset.ResetAsync(r, ct))
            .Get("scan/found", (r, _, ct) => found.GetAsync(r, ct))
            .Get("backup", (r, _, ct) => backup.StateAsync(r, ct))
            .Post("backup/start", (r, _, ct) => backup.StartAsync(r, ct))
            .Post("backup/pause", (r, _, ct) => backup.PauseAsync(r, ct))
            .Post("backup/auto", (r, _, ct) => backup.AutomaticAsync(r, ct))
            .Post("backup/settings", (r, _, ct) => backup.SettingsAsync(r, ct))
            .Get("backup/library", (r, _, ct) => backup.LibraryAsync(r, ct))
            .Get("backup/safe", (r, _, ct) => backup.SafeAsync(r, ct))
            .Post("backup/remove", (r, _, ct) => backup.RemoveAsync(r, ct))
            .Get("backup/phones", (r, _, ct) => backup.PhonesAsync(r, ct))
            .Post("backup/phones/{id}/folder", (r, v, ct) => backup.FolderAsync(r, v["id"], ct))
            .Post("backup/phones/{id}/pause", (r, v, ct) => backup.PausePhoneAsync(r, v["id"], ct))
            .Post("backup/phones/{id}/trips", (r, v, ct) => backup.TripsFolderAsync(r, v["id"], ct))
            .Get("backup/phones/{id}/names", (r, v, ct) => backup.RenamingAsync(r, v["id"], ct))
            .Post("backup/phones/{id}/names", (r, v, ct) => backup.RenameAsync(r, v["id"], ct))
            .Get("cleanup/categories", (r, _, ct) => categories.ReportAsync(r, ct))
            .Post("cleanup/categories/delete", (r, _, ct) => categories.DeleteAsync(r, ct))
            .Get("cleanup/categories/{category}", (r, v, ct) => categories.PhotosAsync(r, v["category"], ct))
            .Get("compress/videos", (r, _, ct) => compress.VideosAsync(r, ct))
            .Get("compress", (r, _, ct) => compress.StateAsync(r, ct))
            .Post("compress/start", (r, _, ct) => compress.StartAsync(r, ct))
            .Post("compress/cancel", (r, _, ct) => compress.CancelAsync(r, ct))
            .Get("notices", (r, _, ct) => notices.StateAsync(r, ct))
            .Post("notices", (r, _, ct) => notices.ChangeAsync(r, ct))
            .Get("notices/opened", (r, _, ct) => notices.OpenedAsync(r, ct))
            .Get("year", (r, _, ct) => year.YearAsync(r, ct))
            .Post("share", (r, _, ct) => year.ShareAsync(r, ct))
            .Post("share/photo", (r, _, ct) => viewer.SharePhotoAsync(r, ct))
            .Get("search", (r, _, ct) => viewer.SearchAsync(r, ct))
            .Get("viewer/details", (r, _, ct) => viewer.DetailsAsync(r, ct))
            .Post("viewer/favorite", (r, _, ct) => viewer.FavoriteAsync(r, ct))
            .Get("fixes", (r, _, ct) => fixes.ReportAsync(r, ct))
            .Post("fixes/dates", (r, _, ct) => fixes.DatesAsync(r, ct))
            .Post("fixes/places", (r, _, ct) => fixes.PlacesAsync(r, ct))
            .Post("fixes/undo", (r, _, ct) => fixes.UndoAsync(r, ct))
            .Post("fixes/names", (r, _, ct) => fixes.NamesAsync(r, ct))
            .Get("vault", (r, _, ct) => vault.StateAsync(r, ct))
            .Post("vault/on", (r, _, ct) => vault.TurnOnAsync(r, ct))
            .Post("vault/recover", (r, _, ct) => vault.RecoverAsync(r, ct))
            .Post("vault/unlock", (r, _, ct) => vault.UnlockAsync(r, ct))
            .Post("vault/lock", (r, _, ct) => vault.LockAsync(r, ct))
            .Get("vault/key", (r, _, ct) => vault.KeyAsync(r, ct))
            .Post("vault/hide", (r, _, ct) => vault.HideAsync(r, ct))
            .Post("vault/unhide", (r, _, ct) => vault.UnhideAsync(r, ct))
            .Post("vault/delete", (r, _, ct) => vault.DeleteAsync(r, ct))
            .Get("vault/{id}/thumbnail", (r, v, ct) => vault.ThumbnailAsync(r, v["id"], ct))
            .Get("vault/{id}/image", (r, v, ct) => vault.ImageAsync(r, v["id"], ct))
            .Get("trips", (r, _, ct) => trips.ListAsync(r, ct))
            .Get("trips/towns", (r, _, ct) => trips.TownsAsync(r, ct))
            .Post("trips/home", (r, _, ct) => trips.HomeAsync(r, ct))
            .Get("trips/{id}", (r, v, ct) => trips.TripAsync(r, v["id"], ct))
            .Post("trips/{id}/folder", (r, v, ct) => trips.FolderAsync(r, v["id"], ct))
            .Post("trips/{id}/name", (r, v, ct) => trips.RenameAsync(r, v["id"], ct))
            .Get("swipe", (r, _, ct) => swipe.StateAsync(r, ct))
            .Post("swipe/decide", (r, _, ct) => swipe.DecideAsync(r, ct))
            .Post("swipe/undo", (r, _, ct) => swipe.UndoAsync(r, ct))
            .Post("swipe/spare", (r, _, ct) => swipe.SpareAsync(r, ct))
            .Post("swipe/delete", (r, _, ct) => swipe.DeleteAsync(r, ct))
            .Get("scan/progress/{instanceId}", (r, v, ct) => progress.GetAsync(r, v["instanceId"], ct))
            .Get("scan/logs", (r, _, ct) => logs.GetPendingAsync(r, ct))
            .Get("organize/files", (r, _, ct) => organize.FilesAsync(r, ct))
            .Get("organize/progress", (r, _, ct) => organize.ProgressAsync(r, ct))
            .Post("organize/plan", (r, _, ct) => organize.PlanAsync(r, ct))
            .Post("organize/apply", (r, _, ct) => organize.ApplyAsync(r, ct))
            .Post("organize/remove", (r, _, ct) => organize.RemoveAsync(r, ct))
            .Post("organize/undo/{batchId}", (r, v, ct) => organize.UndoAsync(r, v["batchId"], ct))
            .Get("organize/batches", (r, _, ct) => organize.BatchesAsync(r, ct))
            .Get("organize/files/{id}/thumbnail", (r, v, ct) => organize.ThumbnailAsync(r, v["id"], ct))
            .Get("organize/files/{id}/image", (r, v, ct) => organize.ImageAsync(r, v["id"], ct))
            .Post("organize/files/{id}/open", (r, v, ct) => organize.OpenAsync(r, v["id"], ct))
            .Get("removed", (r, _, ct) => removed.FindAsync(r, ct))
            .Post("removed/erase", (r, _, ct) => removed.EraseAsync(r, ct))
            .Get("plan", (r, _, ct) => plan.GetAsync(r, ct))
            .Post("plan/buy", (r, _, ct) => plan.BuyAsync(r, ct))
            .Post("plan/restore", (r, _, ct) => plan.RestoreAsync(r, ct))
            .Post("plan/manage", (r, _, ct) => plan.ManageAsync(r, ct))
            .Post("pairing/open", (r, _, ct) => pairing.OpenAsync(r, ct))
            .Post("pairing/close", (r, _, ct) => pairing.CloseAsync(r, ct))
            .Post("pairing/name", (r, _, ct) => pairing.NameAsync(r, ct))
            .Post("pairing/scan", (r, _, ct) => pairing.ScanAsync(r, ct))
            .Post("pairing/code", (r, _, ct) => pairing.CodeAsync(r, ct))
            .Get("pairing/state", (r, _, ct) => pairing.StateAsync(r, ct))
            .Post("pairing/confirm", (r, _, ct) => pairing.ConfirmAsync(r, ct))
            .Post("pairing/stop", (r, _, ct) => pairing.StopAsync(r, ct))
            .Post("send/start", (r, _, ct) => transfer.StartSendingAsync(r, ct))
            .Get("send/state", (r, _, ct) => transfer.SendingAsync(r, ct))
            .Post("send/confirm", (r, _, ct) => transfer.ConfirmSendingAsync(r, ct))
            .Post("send/stop", (r, _, ct) => transfer.StopSendingAsync(r, ct))
            .Post("send/delete-sent", (r, _, ct) => transfer.DeleteSentAsync(r, ct))
            .Get("phones", (r, _, ct) => transfer.PhonesAsync(r, ct))
            .Post("receive/start", (r, _, ct) => transfer.StartReceivingAsync(r, ct))
            .Get("receive/state", (r, _, ct) => transfer.ReceivingAsync(r, ct))
            .Post("receive/confirm", (r, _, ct) => transfer.ConfirmReceivingAsync(r, ct))
            .Post("receive/stop", (r, _, ct) => transfer.StopReceivingAsync(r, ct));
    }

    /// <summary>The addresses, for the program that received a request to ask for its answer.</summary>
    public ApiRouter Router { get; }
}
